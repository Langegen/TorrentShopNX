inline std::string normalizeGenreSeparators(std::string raw) {
    for (const char* separator : {"，", "、", "；", "／", "｜"}) {
        const std::string token(separator);
        size_t pos = 0;
        while ((pos = raw.find(token, pos)) != std::string::npos) {
            raw.replace(pos, token.size(), ",");
            ++pos;
        }
    }
    return raw;
}

